// Derives the component dependency graph from the imports themselves.
//
// Installing a component means copying it and everything it needs. Getting that
// list wrong is the failure mode of copy-in delivery: the user ends up with a
// confirmation dialog and no modal shell, discovers it at build time, and blames
// the kit. Writing the list by hand guarantees it rots, because the person who
// adds an import is never the person who remembers the manifest.
//
// So it is generated, committed, and checked in CI. The skill reads the
// committed file at install time, where it has no build step of its own.
//
//   npm run manifest         write it
//   npm run manifest:check   fail if the committed copy is stale

import { readdir, readFile, writeFile } from "node:fs/promises";
import { join } from "node:path";

const ROOT = new URL("..", import.meta.url).pathname.replace(
  /^\/([A-Za-z]:)/,
  "$1",
);
const DIR = join(ROOT, "skills", "solana-onboarding", "components");
const MANIFEST = join(DIR, "manifest.json");

const IMPORT = /^\s*import\s+(?:type\s+)?(?:[^"']*?\s+from\s+)?["']([^"']+)["']/gm;

async function build() {
  const entries = (await readdir(DIR)).filter((name) =>
    /\.(ts|tsx)$/.test(name),
  );

  const components = {};

  for (const file of entries.sort()) {
    const source = await readFile(join(DIR, file), "utf8");
    const requires = new Set();
    const packages = new Set();

    for (const [, specifier] of source.matchAll(IMPORT)) {
      if (specifier.startsWith("./")) requires.add(specifier.replace("./", ""));
      // React itself is assumed: a project without it cannot use any of this.
      else if (specifier !== "react") packages.add(specifier);
    }

    components[file.replace(/\.tsx?$/, "")] = {
      file,
      client: source.startsWith('"use client"'),
      requires: [...requires].sort(),
      packages: [...packages].sort(),
    };
  }

  // `requires` is what a file imports directly, which is the honest graph and
  // the wrong list to install from: a confirmation dialog needs the callout, and
  // the callout needs the severity palette. Resolving that chain is easy to get
  // subtly wrong once, at install time, in somebody else's project, so it is
  // resolved here instead and shipped as `installs`.
  const closureOf = (name, seen = new Set()) => {
    for (const required of components[name].requires) {
      if (seen.has(required)) continue;
      seen.add(required);
      closureOf(required, seen);
    }
    return seen;
  };

  for (const [name, component] of Object.entries(components)) {
    const closure = closureOf(name);
    const packages = new Set(component.packages);
    for (const required of closure)
      for (const pkg of components[required].packages) packages.add(pkg);

    component.installs = [name, ...closure].sort().map((n) => components[n].file);
    component.installPackages = [...packages].sort();
  }

  return {
    // Read by the skill when it copies components into a project. Generated by
    // scripts/component-manifest.mjs; edit the components, not this file.
    stylesheet: "tokens.css",
    components,
  };
}

const manifest = await build();
const serialised = JSON.stringify(manifest, null, 2) + "\n";

if (process.argv.includes("--check")) {
  // Compared with line endings normalised. Git rewrites them on checkout, so a
  // byte-for-byte comparison reports every Windows working tree as stale while
  // passing on the Linux runner, which is the worst way round for a check to be
  // wrong: it cries wolf where the work happens and stays quiet where it lands.
  const normalise = (text) => text.replace(/\r\n/g, "\n");
  const committed = await readFile(MANIFEST, "utf8").catch(() => "");
  if (normalise(committed) !== normalise(serialised)) {
    console.error(
      "Component manifest is stale. Run `npm run manifest` and commit the result.\n" +
        "It lists what each component needs, and the skill copies from it, so a\n" +
        "stale manifest installs a component with a missing import.",
    );
    process.exit(1);
  }
  console.log("Component manifest matches the components.");
} else {
  await writeFile(MANIFEST, serialised);
  console.log(
    `Wrote manifest for ${Object.keys(manifest.components).length} components.`,
  );
}
